#!/usr/bin/env python3
"""mk_palette.py OUT.hex [OUT.h] -- LTari PAL palette for the frame buffer reader (rtl/atari_fb.v)
and, with OUT.h, the same colours as a C table (8 bits per colour) for the ESP32's screenshots.

256 entries (GTIA colour byte: bits 7:4 hue, 3:0 luminance), one per line, 18 bits hex
{red, green, blue} 6 bits each (the I/O board's DAC takes the top 4).
Computed by us from the ideal UV angles of the PAL GTIA hues (Altirra Hardware Reference
Manual, table 14; LTari/NOTES.md): Y = luminance / 15, U = S cos(angle), V = S sin(angle),
then the PAL YUV -> RGB matrix, clamped. Hue 0 = grey. S = colour saturation.
"""
import math, sys

ANGLE = [None, 135.0, 112.5, 90.0, 67.5, 45.0, 22.5, 337.5, 315.0, 292.5,
         270.0, 225.0, 202.5, 180.0, 157.5, 135.0]
S = 0.18

def rgb(c):
    hue, lum = c >> 4, c & 15
    y = lum / 15.0
    u = v = 0.0
    if hue:
        a = math.radians(ANGLE[hue])
        u, v = S * math.cos(a), S * math.sin(a)
    r = y + 1.140 * v
    g = y - 0.395 * u - 0.581 * v
    b = y + 2.032 * u
    return [max(0, min(63, int(round(x * 63)))) for x in (r, g, b)]

def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    with open(sys.argv[1], 'w') as f:
        for c in range(256):
            r, g, b = rgb(c)
            f.write('%05x\n' % ((r << 12) | (g << 6) | b))
    if len(sys.argv) == 3:
        with open(sys.argv[2], 'w') as f:
            f.write('/* atari_palette.h -- generated by LTari/tools/mk_palette.py: the frame buffer\'s 256\n'
                    ' * colours (rtl/atari_palette.hex) as {r, g, b}, 6-bit values widened to 8 bits */\n')
            f.write('static const uint8_t atari_pal[256][3] = {\n')
            for c in range(256):
                v = [(x << 2) | (x >> 4) for x in rgb(c)]
                f.write('    {0x%02X, 0x%02X, 0x%02X},%s' % (v[0], v[1], v[2], '\n' if c % 4 == 3 else ''))
            f.write('};\n')

main()
