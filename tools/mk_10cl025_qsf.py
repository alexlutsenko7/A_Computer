#!/usr/bin/env python3
"""mk_10cl025_qsf.py -- make the 10cl025/ Quartus projects from the ep4_ce15/ ones.

Each machine folder has ep4_ce15/ (QMTECH Cyclone IV EP4CE15F23 core board: all sources) and 10cl025/ (QMTECH
Cyclone 10 LP 10CL025YU256 core board: project files only; the sources, the .sdc and the ROM images are ep4_ce15's).
The 10cl025 .qsf is the ep4_ce15 .qsf with the device, every ball name and the file paths translated:
  - on-board parts and the SDRAM by signal, the I/O board's signals by their pin of header U8
    (U8 has the same place, direction and power pins on both boards; pins 7-60 are I/O on both);
  - KEY1 (the 10CL025 board has one user key) goes to header U7 pin 7 with a weak pull-up: a place for a
    second button to ground; the board's nCONFIG button returns to the machine menu as well.
Run from the project root after changing an ep4_ce15 .qsf:   python3 tools/mk_10cl025_qsf.py
"""
import os, re, sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else '.')
PROJECTS = [('AMenu', 'AMenu'), ('LSpectrum', 'LSpectrum'), ('L64', 'L64'), ('LTari', 'LTari'), ('LTari', 'LTari800')]
DEVICE = '10CL025YU256I7G'

# header U8, pin -> ball (docs/BOARD_PINOUT.md; 10CL025: schematic V1 2023-11-09, sheet 2)
U8_EP4 = {7: 'AA13', 8: 'AB13', 9: 'AA14', 10: 'AB14', 11: 'AA15', 12: 'AB15', 13: 'AA16', 14: 'AB16', 15: 'AA17',
          16: 'AB17', 17: 'AA18', 18: 'AB18', 19: 'AA19', 20: 'AB19', 21: 'AA20', 22: 'AB20', 23: 'Y22', 24: 'Y21',
          25: 'W22', 26: 'W21', 27: 'V22', 28: 'V21', 29: 'U22', 30: 'U21', 31: 'R22', 32: 'R21', 33: 'P22', 34: 'P21',
          35: 'N22', 36: 'N21', 37: 'M22', 38: 'M21', 39: 'L22', 40: 'L21', 41: 'K22', 42: 'K21', 43: 'J22', 44: 'J21',
          45: 'H22', 46: 'H21', 47: 'F22', 48: 'F21', 49: 'E22', 50: 'E21', 51: 'D22', 52: 'D21', 53: 'C22', 54: 'C21',
          55: 'B22', 56: 'B21', 57: 'N20', 58: 'N19', 59: 'M20', 60: 'M19'}
U8_C10 = {7: 'R11', 8: 'T11', 9: 'R12', 10: 'T12', 11: 'M10', 12: 'P9', 13: 'P11', 14: 'N11', 15: 'R13', 16: 'T13',
          17: 'R14', 18: 'T14', 19: 'N12', 20: 'T15', 21: 'N14', 22: 'P14', 23: 'P15', 24: 'R16', 25: 'N15', 26: 'P16',
          27: 'L15', 28: 'N16', 29: 'L16', 30: 'L13', 31: 'L14', 32: 'K15', 33: 'K16', 34: 'J13', 35: 'J14', 36: 'F13',
          37: 'D12', 38: 'F14', 39: 'J16', 40: 'J15', 41: 'G16', 42: 'G15', 43: 'F16', 44: 'F15', 45: 'D15', 46: 'D16',
          47: 'D14', 48: 'C14', 49: 'C16', 50: 'C15', 51: 'B16', 52: 'A15', 53: 'B14', 54: 'A14', 55: 'B13', 56: 'A13',
          57: 'B12', 58: 'A12', 59: 'B11', 60: 'A11'}
# 10CL025 pins that are dual-purpose configuration pins (not used by the I/O board's signals today)
C10_CONFIG_PINS = {'J16', 'J15', 'G16', 'G15', 'F16', 'F15'}

# on-board parts, by signal
ONBOARD = {'CLOCK_50': 'E2', 'RESET_N': 'F3', 'KEY1': 'G1', 'LEDR': 'N9',
           'DRAM_CLK': 'P2', 'DRAM_CKE': 'R1', 'DRAM_CS_N': 'P8', 'DRAM_RAS_N': 'M8', 'DRAM_CAS_N': 'M7',
           'DRAM_WE_N': 'P6', 'DRAM_LDQM': 'N6', 'DRAM_UDQM': 'P1', 'DRAM_BA[0]': 'N8', 'DRAM_BA[1]': 'L8'}
for i, b in enumerate('R7 T7 T10 R10 R6 T5 R5 T4 R4 T3 T6 R3 T2'.split()):
    ONBOARD['DRAM_ADDR[%d]' % i] = b
for i, b in enumerate('K5 L3 L4 L7 N3 M6 P3 N5 N2 N1 L1 L2 K1 K2 J1 J2'.split()):
    ONBOARD['DRAM_DQ[%d]' % i] = b
EP4_TO_U8 = {b: p for p, b in U8_EP4.items()}

HEAD = '''# %s for the QMTECH Cyclone 10 LP core board (10CL025YU256I7G) + the I/O board on header U8.
# GENERATED by tools/mk_10cl025_qsf.py from ../ep4_ce15/%s.qsf: change that file (or the tool) and run the tool again.
# Sources, the .sdc and the ROM images are ../ep4_ce15's; this folder holds only the project and its outputs.
'''
PATH_KEYS = ('VERILOG_FILE', 'SYSTEMVERILOG_FILE', 'VHDL_FILE', 'SDC_FILE', 'SEARCH_PATH', 'QIP_FILE', 'MIF_FILE', 'HEX_FILE')

def convert(folder, rev):
    src = os.path.join(ROOT, folder, 'ep4_ce15', rev + '.qsf')
    out, used = [HEAD % (rev, rev)], {}
    for l in open(src, encoding='utf-8').read().replace('\r\n', '\n').split('\n'):
        m = re.match(r'set_global_assignment -name (\w+) (.*)$', l)
        if m and m.group(1) == 'FAMILY':
            l = 'set_global_assignment -name FAMILY "Cyclone 10 LP"'
        elif m and m.group(1) == 'DEVICE':
            l = 'set_global_assignment -name DEVICE ' + DEVICE
        elif m and m.group(1) in ('MIN_CORE_JUNCTION_TEMP', 'MAX_CORE_JUNCTION_TEMP'):
            continue                                   # the device's own range (I7: -40..100 C)
        elif m and m.group(1) in PATH_KEYS:
            p = m.group(2).strip().strip('"')
            if not p.startswith('../../'):
                l = 'set_global_assignment -name %s ../ep4_ce15/%s' % (m.group(1), p)
        m = re.match(r'set_location_assignment PIN_(\w+) -to (\S+)(.*)$', l)
        if m:
            ball, sig, rest = m.groups()
            if sig in ONBOARD:
                new, rest = ONBOARD[sig], ('      # header U7 pin 7 (free): a second button to ground may be wired here'
                                           if sig == 'KEY1' else '')
            elif ball in EP4_TO_U8:
                new = U8_C10[EP4_TO_U8[ball]]
                if new in C10_CONFIG_PINS:
                    sys.exit('%s: %s lands on configuration pin %s' % (rev, sig, new))
            else:
                sys.exit('%s: no translation for %s at %s' % (rev, sig, ball))
            if new in used:
                sys.exit('%s: %s and %s both at %s' % (rev, sig, used[new], new))
            used[new] = sig
            l = 'set_location_assignment PIN_%s -to %s%s' % (new, sig, rest)
        out.append(l)
    text = '\n'.join(out).rstrip('\n') + '\n'
    text += '# flash_if.v: the Cyclone 10 LP variant of the active-serial block\nset_global_assignment -name VERILOG_MACRO "CYCLONE10LP=1"\n'
    if rev == 'AMenu':                                # AMenu.v's defaults are relative to its own project folder
        text += ('set_parameter -name FONT_HEX "../ep4_ce15/rtl/menu_font.hex"\n'
                 'set_parameter -name TEXT_HEX "../ep4_ce15/rtl/menu_text.hex"\n')
    if 'KEY1' in used.values():
        text += 'set_instance_assignment -name WEAK_PULL_UP_RESISTOR ON -to KEY1\n'
    extra = os.path.join(ROOT, folder, '10cl025', rev + '.extra.qsf')      # hand-written additions, kept by the tool
    if os.path.exists(extra):
        text += '\n# from %s.extra.qsf\n' % rev + open(extra, encoding='utf-8').read()
    d = os.path.join(ROOT, folder, '10cl025')
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, rev + '.qsf'), 'w', newline='\n').write(text)
    qpf = os.path.join(d, folder + '.qpf')
    revs = [r for f, r in PROJECTS if f == folder]
    open(qpf, 'w', newline='\n').write('QUARTUS_VERSION = "25.1"\n' + ''.join('PROJECT_REVISION = "%s"\n' % r for r in revs))
    print('%-10s %-9s %d pins' % (folder, rev, len(used)))

for f, r in PROJECTS:
    convert(f, r)
